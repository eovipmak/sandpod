#!/usr/bin/env bash
# Add (or update) a port app: nginx server block + supervisord program + reloads.
# Run as root. Idempotent for the same (domain, port, command).
# Usage: add-port-app.sh <service-user> <container> <domain> --port 3001 --command "node server.js" [--primary]
#   --primary uses ~/data/public_html as the working dir; default uses ~/data/<domain>.
#   Port must be 3000-3999 (panel allocates; scripts never invent one).
#   Command runs as `customer` inside the container, no shell unless wrapped
#   explicitly (e.g. --command "/bin/sh -c '...'"). It must listen on 127.0.0.1:<port>.
set -euo pipefail

[[ $# -ge 5 ]] || { echo "Usage: $0 <service-user> <container> <domain> --port 3001 --command \"<cmd>\" [--primary]" >&2; exit 2; }
SERVICE_USER="$1"; CONTAINER="$2"; DOMAIN="${3,,}"; shift 3
PORT=""; APP_CMD=""; PRIMARY=0
while [[ $# -gt 0 ]]; do case "$1" in
  --port) PORT="${2:-}"; shift 2 ;;
  --command) APP_CMD="${2:-}"; shift 2 ;;
  --primary) PRIMARY=1; shift ;;
  *) echo "Unknown arg: $1" >&2; exit 2 ;;
esac; done

[[ "${EUID}" -eq 0 ]] || { echo "Run as root." >&2; exit 1; }
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "${SCRIPT_DIR}/lib.sh"

valid_domain "$DOMAIN" || { echo "Invalid domain: $DOMAIN" >&2; exit 2; }
[[ -n "$PORT" ]] || { echo "Missing --port (3000-3999, panel-allocated)." >&2; exit 2; }
valid_port "$PORT" || { echo "Invalid --port ${PORT} (want 3000-3999)." >&2; exit 2; }
[[ -n "${APP_CMD//[[:space:]]/}" ]] || { echo "Missing --command." >&2; exit 2; }
[[ "$APP_CMD" != *$'\n'* ]] || { echo "Command must be a single line." >&2; exit 2; }

ensure_app_dirs
ensure_nginx_sites_include

if [[ "$PRIMARY" -eq 1 ]]; then
    APP_DIR="/srv/customer/public_html"
else
    install -d -m 0755 "${HOME_DIR}/data/${DOMAIN}"
    chown "${SERVICE_USER}:${SERVICE_USER}" "${HOME_DIR}/data/${DOMAIN}"
    APP_DIR="/srv/customer/${DOMAIN}"
fi

SITE_CONF="${SITES_DIR}/${DOMAIN}.conf"
SUP_CONF="${SUPERVISOR_DIR}/${DOMAIN}.conf"
PROG="$(program_for_domain "$DOMAIN")"

# Back up everything we touch so a failed reload can roll back.
cp -a "$NGINX_CONF" "${NGINX_CONF}.bak"
[[ -f "$SITE_CONF" ]] && cp -a "$SITE_CONF" "${SITE_CONF}.bak" || true
[[ -f "$SUP_CONF" ]] && cp -a "$SUP_CONF" "${SUP_CONF}.bak" || true

rollback() {
    echo "Reload failed, restoring backup." >&2
    mv "${NGINX_CONF}.bak" "$NGINX_CONF"
    if [[ -f "${SITE_CONF}.bak" ]]; then mv "${SITE_CONF}.bak" "$SITE_CONF"; else rm -f "$SITE_CONF"; fi
    if [[ -f "${SUP_CONF}.bak" ]]; then mv "${SUP_CONF}.bak" "$SUP_CONF"; else rm -f "$SUP_CONF"; fi
}

# A port-app server block (exact server_name) shadows the catch-all PHP
# server, so drop the PHP map entries to keep list-sites truthful.
map_del site_root "$DOMAIN" || true
map_del php_fpm_backend "$DOMAIN" || true

cat > "$SITE_CONF" <<EOF
# Generated by customer-apps/add-port-app.sh - do not hand-edit.
server {
    listen 80;
    server_name ${DOMAIN};

    location / {
        proxy_pass http://127.0.0.1:${PORT};
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
chown "${SERVICE_USER}:${SERVICE_USER}" "$SITE_CONF"
chmod 0644 "$SITE_CONF"

cat > "$SUP_CONF" <<EOF
# Generated by customer-apps/add-port-app.sh - do not hand-edit.
[program:${PROG}]
command=${APP_CMD}
directory=${APP_DIR}
user=customer
autorestart=true
stdout_logfile=/dev/fd/1
stdout_logfile_maxbytes=0
stderr_logfile=/dev/fd/2
stderr_logfile_maxbytes=0
EOF
chown "${SERVICE_USER}:${SERVICE_USER}" "$SUP_CONF"
chmod 0644 "$SUP_CONF"

if ! nginx_test_reload; then
    rollback
    exit 1
fi
if ! supervisor_reread_update; then
    rollback
    nginx_test_reload || true
    supervisor_reread_update || true
    exit 1
fi
rm -f "${NGINX_CONF}.bak" "${SITE_CONF}.bak" "${SUP_CONF}.bak"
echo "Port app ${DOMAIN}: port=${PORT} program=${PROG} dir=${APP_DIR}"
container_exec supervisorctl status "$PROG" || true
