package apps

import (
	"fmt"
	"os"
	"strings"

	"sandpodctl/internal/platform"
)

// AddPortApp ports add-port-app.sh.
func AddPortApp(args []string) int {
	if len(args) < 5 {
		fmt.Fprintln(os.Stderr, `Usage: add-port-app <service-user> <container> <domain> --port 3001 --command "<cmd>" [--primary]`)
		return 2
	}
	svc, cont, domain := args[0], args[1], strings.ToLower(args[2])
	var port, appCmd string
	primary := false
	rest := args[3:]
	for i := 0; i < len(rest); i++ {
		switch rest[i] {
		case "--port":
			if i+1 >= len(rest) {
				fmt.Fprintln(os.Stderr, "Missing --port value.")
				return 2
			}
			port = rest[i+1]
			i++
		case "--command":
			if i+1 >= len(rest) {
				fmt.Fprintln(os.Stderr, "Missing --command value.")
				return 2
			}
			appCmd = rest[i+1]
			i++
		case "--primary":
			primary = true
		default:
			fmt.Fprintf(os.Stderr, "Unknown arg: %s\n", rest[i])
			return 2
		}
	}
	if code := platform.MustRoot(); code != -1 {
		return code
	}
	ctx, code := Load(svc, cont)
	if code != 0 {
		return code
	}
	if !platform.ValidDomain(domain) {
		fmt.Fprintf(os.Stderr, "Invalid domain: %s\n", domain)
		return 2
	}
	if port == "" {
		fmt.Fprintln(os.Stderr, "Missing --port (3000-3999, panel-allocated).")
		return 2
	}
	if !platform.ValidPort3000(port) {
		fmt.Fprintf(os.Stderr, "Invalid --port %s (want 3000-3999).\n", port)
		return 2
	}
	if strings.TrimSpace(appCmd) == "" {
		fmt.Fprintln(os.Stderr, "Missing --command.")
		return 2
	}
	if strings.Contains(appCmd, "\n") {
		fmt.Fprintln(os.Stderr, "Command must be a single line.")
		return 2
	}
	if err := ctx.EnsureAppDirs(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	if err := platform.EnsureSitesInclude(ctx.NginxConf); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	var appDir string
	if primary {
		appDir = "/srv/customer/public_html"
	} else {
		dir := ctx.Home + "/data/" + domain
		if err := platform.MkdirOwn(0755, svc, svc, dir); err != nil {
			fmt.Fprintln(os.Stderr, err)
			return 1
		}
		appDir = "/srv/customer/" + domain
	}
	siteConf := ctx.SitesDir + "/" + domain + ".conf"
	supConf := ctx.SupervisorDir + "/" + domain + ".conf"
	prog := platform.ProgramForDomain(domain)

	if err := platform.CopyFile(ctx.NginxConf, ctx.NginxConf+".bak"); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	copyIfExists := func(s, d string) {
		if _, err := os.Stat(s); err == nil {
			_ = platform.CopyFile(s, d)
		}
	}
	copyIfExists(siteConf, siteConf+".bak")
	copyIfExists(supConf, supConf+".bak")
	rollback := func() {
		fmt.Fprintln(os.Stderr, "Reload failed, restoring backup.")
		_ = os.Rename(ctx.NginxConf+".bak", ctx.NginxConf)
		if _, err := os.Stat(siteConf + ".bak"); err == nil {
			_ = os.Rename(siteConf+".bak", siteConf)
		} else {
			_ = os.Remove(siteConf)
		}
		if _, err := os.Stat(supConf + ".bak"); err == nil {
			_ = os.Rename(supConf+".bak", supConf)
		} else {
			_ = os.Remove(supConf)
		}
	}
	_ = platform.MapDel(ctx.NginxConf, "site_root", domain)
	_ = platform.MapDel(ctx.NginxConf, "php_fpm_backend", domain)

	siteContent := fmt.Sprintf(`# Generated by customer-apps/add-port-app - do not hand-edit.
server {
    listen 80;
    server_name %s;

    location / {
        proxy_pass http://127.0.0.1:%s;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }
}
`, domain, port)
	if err := os.WriteFile(siteConf, []byte(siteContent), 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		rollback()
		return 1
	}
	_ = platform.Chown(siteConf, svc, svc)
	supContent := fmt.Sprintf(`# Generated by customer-apps/add-port-app - do not hand-edit.
[program:%s]
command=%s
directory=%s
user=customer
autorestart=true
stdout_logfile=/dev/fd/1
stdout_logfile_maxbytes=0
stderr_logfile=/dev/fd/2
stderr_logfile_maxbytes=0
`, prog, appCmd, appDir)
	if err := os.WriteFile(supConf, []byte(supContent), 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		rollback()
		return 1
	}
	_ = platform.Chown(supConf, svc, svc)

	if err := ctx.NginxTestReload(); err != nil {
		rollback()
		return 1
	}
	if err := ctx.SupervisorRereadUpdate(); err != nil {
		rollback()
		_ = ctx.NginxTestReload()
		_ = ctx.SupervisorRereadUpdate()
		return 1
	}
	_ = os.Remove(ctx.NginxConf + ".bak")
	_ = os.Remove(siteConf + ".bak")
	_ = os.Remove(supConf + ".bak")
	fmt.Printf("Port app %s: port=%s program=%s dir=%s\n", domain, port, prog, appDir)
	_ = ctx.containerExec("supervisorctl", "status", prog)
	return 0
}

// RemovePortApp ports remove-port-app.sh.
func RemovePortApp(args []string) int {
	if len(args) < 3 {
		fmt.Fprintln(os.Stderr, "Usage: remove-port-app <service-user> <container> <domain> [--delete-data]")
		return 2
	}
	svc, cont, domain := args[0], args[1], strings.ToLower(args[2])
	delData := false
	for _, a := range args[3:] {
		if a == "--delete-data" {
			delData = true
		} else {
			fmt.Fprintf(os.Stderr, "Unknown arg: %s\n", a)
			return 2
		}
	}
	if code := platform.MustRoot(); code != -1 {
		return code
	}
	ctx, code := Load(svc, cont)
	if code != 0 {
		return code
	}
	if !platform.ValidDomain(domain) {
		fmt.Fprintf(os.Stderr, "Invalid domain: %s\n", domain)
		return 2
	}
	siteConf := ctx.SitesDir + "/" + domain + ".conf"
	supConf := ctx.SupervisorDir + "/" + domain + ".conf"
	if _, err := os.Stat(siteConf); err != nil {
		if _, err2 := os.Stat(supConf); err2 != nil {
			fmt.Printf("No port app for %s (nothing to do).\n", domain)
			return 0
		}
	}
	if err := platform.CopyFile(ctx.NginxConf, ctx.NginxConf+".bak"); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	if _, err := os.Stat(siteConf); err == nil {
		_ = platform.CopyFile(siteConf, siteConf+".bak")
	}
	if _, err := os.Stat(supConf); err == nil {
		_ = platform.CopyFile(supConf, supConf+".bak")
	}
	_ = os.Remove(siteConf)
	_ = os.Remove(supConf)
	rollback := func() {
		_ = os.Rename(ctx.NginxConf+".bak", ctx.NginxConf)
		if _, err := os.Stat(siteConf + ".bak"); err == nil {
			_ = os.Rename(siteConf+".bak", siteConf)
		}
		if _, err := os.Stat(supConf + ".bak"); err == nil {
			_ = os.Rename(supConf+".bak", supConf)
		}
	}
	if err := ctx.NginxTestReload(); err != nil {
		fmt.Fprintln(os.Stderr, "Reload failed, restoring backup.")
		rollback()
		return 1
	}
	if err := ctx.SupervisorRereadUpdate(); err != nil {
		fmt.Fprintln(os.Stderr, "Supervisor update failed, restoring backup.")
		rollback()
		_ = ctx.NginxTestReload()
		_ = ctx.SupervisorRereadUpdate()
		return 1
	}
	_ = os.Remove(ctx.NginxConf + ".bak")
	_ = os.Remove(siteConf + ".bak")
	_ = os.Remove(supConf + ".bak")
	if delData {
		_ = os.RemoveAll(ctx.Home + "/data/" + domain)
		fmt.Printf("Deleted data for %s.\n", domain)
	}
	fmt.Printf("Removed port app %s.\n", domain)
	return 0
}
