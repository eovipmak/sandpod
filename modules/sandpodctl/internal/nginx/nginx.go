// Package nginx ports modules/host-nginx/scripts.
package nginx

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"sandpodctl/internal/platform"
)

// GenerateSiteConf ports generate-site-conf.sh.
func GenerateSiteConf(args []string) int {
	prune := false
	for _, a := range args {
		if a == "--prune" {
			prune = true
		} else {
			fmt.Fprintf(os.Stderr, "Unknown arg: %s\n", a)
			return 2
		}
	}
	registry := envOr("REGISTRY", "/etc/sandpod/sites.tsv")
	customers := envOr("CUSTOMERS", "/etc/sandpod/customers.tsv")
	outDir := envOr("OUT_DIR", "/etc/nginx/conf.d")
	if _, err := os.Stat(customers); err != nil {
		fmt.Fprintf(os.Stderr, "Missing %s (provision a customer first).\n", customers)
		return 1
	}
	if _, err := os.Stat(registry); err != nil {
		fmt.Fprintf(os.Stderr, "Missing %s. Create it, one '<instance><TAB><domain>' per line.\n", registry)
		fmt.Fprintf(os.Stderr, "Example: printf '002\\texample002.test\\n' > %s\n", registry)
		return 1
	}
	webPort := map[string]string{}
	if raw, err := os.ReadFile(customers); err == nil {
		for _, line := range strings.Split(string(raw), "\n") {
			t := strings.TrimRight(line, "\r")
			if t == "" || strings.HasPrefix(t, "#") {
				continue
			}
			parts := strings.Split(t, "\t")
			if len(parts) < 5 {
				continue
			}
			inst, web := parts[0], parts[3]
			if !regexp.MustCompile(`^[0-9]+$`).MatchString(web) {
				fmt.Fprintf(os.Stderr, "Instance %s has bad web_port '%s'; skipping.\n", inst, web)
				continue
			}
			var n int
			fmt.Sscanf(web, "%d", &n)
			if n < 1 || n > 65535 {
				fmt.Fprintf(os.Stderr, "Instance %s has bad web_port '%s'; skipping.\n", inst, web)
				continue
			}
			webPort[inst] = web
		}
	}
	domains := map[string][]string{}
	seen := map[string]string{}
	domainRe := regexp.MustCompile(`^[A-Za-z0-9]([A-Za-z0-9_.-]*[A-Za-z0-9])?$`)
	if raw, err := os.ReadFile(registry); err == nil {
		for _, line := range strings.Split(string(raw), "\n") {
			t := strings.TrimRight(line, "\r")
			if t == "" || strings.HasPrefix(t, "#") {
				continue
			}
			parts := strings.Split(t, "\t")
			if len(parts) < 2 {
				continue
			}
			inst, domain := parts[0], parts[1]
			if inst == "" || domain == "" {
				continue
			}
			if !domainRe.MatchString(domain) {
				fmt.Fprintf(os.Stderr, "Bad domain '%s' for instance %s; skipping.\n", domain, inst)
				continue
			}
			if owner, ok := seen[domain]; ok && owner != inst {
				fmt.Fprintf(os.Stderr, "Domain %s claimed by %s and %s; keeping first.\n", domain, owner, inst)
				continue
			}
			seen[domain] = inst
			domains[inst] = append(domains[inst], domain)
		}
	}
	if len(domains) == 0 {
		fmt.Fprintf(os.Stderr, "No domains in %s.\n", registry)
		return 1
	}
	sanitize := regexp.MustCompile(`[^A-Za-z0-9_.-]`)
	sanitizeInst := regexp.MustCompile(`[^A-Za-z0-9_-]`)
	var insts []string
	for k := range domains {
		insts = append(insts, k)
	}
	sort.Strings(insts)
	for _, inst := range insts {
		web, ok := webPort[inst]
		if !ok {
			fmt.Fprintf(os.Stderr, "Instance %s has domains but no registry entry; skipping.\n", inst)
			continue
		}
		names := strings.Join(domains[inst], " ")
		safe := sanitize.ReplaceAllString(names, "_")
		if safe != names {
			fmt.Fprintf(os.Stderr, "Instance %s: sanitized names; skipping.\n", inst)
			continue
		}
		safeInst := sanitizeInst.ReplaceAllString(inst, "_")
		out := filepath.Join(outDir, "sandpod-"+safeInst+".conf")
		content := fmt.Sprintf(`# Generated by sandpod host-nginx from %s + %s - do not hand-edit.
upstream sandpod_customer_%s {
    server 127.0.0.1:%s max_fails=2 fail_timeout=10s;
    keepalive 16;
}

server {
    listen 80;
    server_name %s;

    location / {
        proxy_pass http://sandpod_customer_%s;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Connection "";
        proxy_connect_timeout 5s;
        proxy_read_timeout 60s;
    }

    access_log /var/log/nginx/sandpod-%s-access.log;
    error_log /var/log/nginx/sandpod-%s-error.log warn;
}
`, customers, registry, safeInst, web, names, safeInst, safeInst, safeInst)
		if err := os.WriteFile(out, []byte(content), 0644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			return 1
		}
		fmt.Printf("Wrote %s (%s -> 127.0.0.1:%s)\n", out, names, web)
	}
	if enforcing() {
		matches, _ := filepath.Glob(filepath.Join(outDir, "sandpod-*.conf"))
		if len(matches) > 0 {
			args := append([]string{"-F"}, matches...)
			_ = exec.Command("restorecon", args...).Run()
		}
	}
	matches, _ := filepath.Glob(filepath.Join(outDir, "sandpod-*.conf"))
	var stale []string
	for _, conf := range matches {
		base := filepath.Base(conf)
		id := strings.TrimSuffix(strings.TrimPrefix(base, "sandpod-"), ".conf")
		if _, ok := domains[id]; !ok {
			if _, ok2 := webPort[id]; !ok2 {
				stale = append(stale, conf)
			}
		}
	}
	sort.Strings(stale)
	if prune {
		for _, conf := range stale {
			id := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(conf), "sandpod-"), ".conf")
			fmt.Printf("Pruning stale %s (instance %s not in registry).\n", conf, id)
			_ = os.Remove(conf)
		}
	} else {
		for _, conf := range stale {
			id := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(conf), "sandpod-"), ".conf")
			fmt.Fprintf(os.Stderr, "WARNING: stale %s (instance %s not in registry; re-run with --prune to delete).\n", conf, id)
		}
	}
	fmt.Println("Next: sandpodctl reload-host-nginx")
	return 0
}

// ReloadHostNginx ports reload-host-nginx.sh.
func ReloadHostNginx(args []string) int {
	if len(args) != 0 {
		fmt.Fprintln(os.Stderr, "Usage: reload-host-nginx (no args)")
		return 2
	}
	if code := platform.MustRoot(); code != -1 {
		return code
	}
	t := exec.Command("nginx", "-t")
	t.Stdout, t.Stderr = os.Stdout, os.Stderr
	if err := t.Run(); err != nil {
		return 1
	}
	r := exec.Command("systemctl", "reload", "nginx")
	r.Stdout, r.Stderr = os.Stdout, os.Stderr
	if err := r.Run(); err != nil {
		return 1
	}
	fmt.Println("Host nginx reloaded.")
	return 0
}

func envOr(k, def string) string {
	if v := os.Getenv(k); v != "" {
		return v
	}
	return def
}

func enforcing() bool {
	if !platform.Have("getenforce") {
		return false
	}
	out, err := exec.Command("getenforce").Output()
	return err == nil && strings.TrimSpace(string(out)) == "Enforcing"
}
