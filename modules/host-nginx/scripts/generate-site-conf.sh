#!/usr/bin/env bash
# Generate host-nginx per-customer proxy configs from the fleet registry +
# a domain map. Run as root.
#
# Inputs:
#   /etc/sandpod/customers.tsv   instance, service_user, container, web_port, ssh_port, image
#   /etc/sandpod/sites.tsv       instance, domain (one per line, '#' comments).
#     First domain of an instance is canonical; the rest become server_name aliases.
#     Example:
#       001     shop.example.com
#       001     www.shop.example.com
#       002     example002.test
#
# Output: /etc/nginx/conf.d/sandpod-<instance>.conf (one server block each).
# Then run reload-host-nginx.sh.
set -euo pipefail

REGISTRY="${REGISTRY:-/etc/sandpod/sites.tsv}"
CUSTOMERS="${CUSTOMERS:-/etc/sandpod/customers.tsv}"
OUT_DIR="${OUT_DIR:-/etc/nginx/conf.d}"
TEMPLATE="${TEMPLATE:-}"

[[ -f "$CUSTOMERS" ]] || { echo "Missing $CUSTOMERS (provision a customer first)." >&2; exit 1; }
[[ -f "$REGISTRY" ]] || {
    echo "Missing $REGISTRY. Create it, one '<instance><TAB><domain>' per line." >&2
    echo "Example: printf '002\\texample002.test\\n' > $REGISTRY" >&2
    exit 1
}

declare -A WEB_PORT=()
while IFS=$'\t' read -r inst user cont web ssh img; do
    [[ "$inst" =~ ^#.*$ || -z "$inst" ]] && continue
    WEB_PORT["$inst"]="$web"
done < "$CUSTOMERS"

declare -A DOMAINS=()
while IFS=$'\t' read -r inst domain _rest; do
    [[ "$inst" =~ ^#.*$ || -z "$inst" ]] && continue
    [[ -z "${domain:-}" ]] && continue
    if [[ -z "${DOMAINS[$inst]:-}" ]]; then DOMAINS["$inst"]="$domain";
    else DOMAINS["$inst"]="${DOMAINS[$inst]} $domain"; fi
done < "$REGISTRY"

[[ ${#DOMAINS[@]} -gt 0 ]] || { echo "No domains in $REGISTRY." >&2; exit 1; }

for inst in "${!DOMAINS[@]}"; do
    web="${WEB_PORT[$inst]:-}"
    [[ -n "$web" ]] || { echo "Instance $inst has domains but no registry entry; skipping." >&2; continue; }
    names="${DOMAINS[$inst]}"
    # shellcheck disable=SC2001
    safe_inst="$(printf '%s' "$inst" | sed 's/[^A-Za-z0-9_-]/_/g')"
    out="${OUT_DIR}/sandpod-${safe_inst}.conf"
    {
        echo "# Generated by sandpod host-nginx from ${CUSTOMERS} + ${REGISTRY} - do not hand-edit."
        echo "upstream sandpod_customer_${safe_inst} {"
        echo "    server 127.0.0.1:${web} max_fails=2 fail_timeout=10s;"
        echo "    keepalive 16;"
        echo "}"
        echo ""
        echo "server {"
        echo "    listen 80;"
        echo "    server_name ${names};"
        echo ""
        echo "    location ^~ /.well-known/acme-challenge/ {"
        echo "        root /var/www/html;"
        echo "    }"
        echo ""
        echo "    location / {"
        echo "        proxy_pass http://sandpod_customer_${safe_inst};"
        echo "        proxy_http_version 1.1;"
        echo "        proxy_set_header Host \$host;"
        echo "        proxy_set_header X-Real-IP \$remote_addr;"
        echo "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;"
        echo "        proxy_set_header X-Forwarded-Proto \$scheme;"
        echo "        proxy_set_header Connection \"\";"
        echo "        proxy_connect_timeout 5s;"
        echo "        proxy_read_timeout 60s;"
        echo "    }"
        echo ""
        echo "    access_log /var/log/nginx/sandpod-${safe_inst}-access.log;"
        echo "    error_log /var/log/nginx/sandpod-${safe_inst}-error.log warn;"
        echo "}"
    } > "$out"
    chmod 0644 "$out"
    echo "Wrote $out (${names} -> 127.0.0.1:${web})"
done
echo "Next: $(dirname "$0")/reload-host-nginx.sh"
